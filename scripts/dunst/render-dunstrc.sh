#!/bin/sh
# Generate a square Dunst theme from the active DWM colorscheme.
set -eu

palette=${1:-"$HOME/.cache/dwm-colorscheme/colors.sh"}
fallback="$HOME/.config/suckless/scripts/colorschemes/monokai.sh"
config_dir="$HOME/.config/dunst"
config="$config_dir/dunstrc"

if [ -r "$palette" ]; then
    # shellcheck disable=SC1090
    . "$palette"
elif [ -r "$fallback" ]; then
    # shellcheck disable=SC1090
    . "$fallback"
else
    printf 'render-dunstrc: no readable palette found\n' >&2
    exit 1
fi

: "${BG:?}" "${FG:?}" "${COMMENT:?}" "${RED:?}" "${BLUE:?}" \
  "${CYAN:?}" "${MAUVE:?}"

mkdir -p "$config_dir"
tmp=$(mktemp "$config_dir/.dunstrc.XXXXXX")
trap 'rm -f "$tmp"' EXIT HUP INT TERM

cat > "$tmp" <<EOF
# Generated by ~/.config/suckless/scripts/dunst/render-dunstrc.sh.
# Edit the renderer in the Suckless project; this file is replaced on theme changes.

[global]
    monitor = 0
    follow = keyboard
    width = 360
    height = (0, 300)
    origin = top-right
    offset = (15, 37)
    scale = 0
    notification_limit = 5

    progress_bar = true
    progress_bar_height = 10
    progress_bar_frame_width = 2
    progress_bar_min_width = 120
    progress_bar_max_width = 340
    progress_bar_corner_radius = 0
    icon_corner_radius = 0

    indicate_hidden = true
    transparency = 0
    separator_height = 0
    padding = 8
    horizontal_padding = 8
    text_icon_padding = 8
    frame_width = 2
    gap_size = 8
    separator_color = frame
    sort = true

    font = Monofur Nerd Font Propo 14
    line_height = 2
    markup = full
    format = "<b>%s</b>\n%b"
    alignment = left
    vertical_alignment = center
    show_age_threshold = 60
    ellipsize = end
    ignore_newline = false
    stack_duplicates = true
    hide_duplicate_count = false
    show_indicators = true

    enable_recursive_icon_lookup = true
    icon_theme = "Papirus-Dark, breeze-dark, Adwaita"
    icon_position = left
    min_icon_size = 32
    max_icon_size = 48
    history_length = 20
    browser = /usr/bin/xdg-open

    corner_radius = 0
    corners = all
    mouse_left_click = close_current
    mouse_middle_click = do_action, close_current
    mouse_right_click = close_all

[urgency_low]
    background = "#${BG}"
    foreground = "#${COMMENT}"
    frame_color = "#${COMMENT}"
    highlight = "#${CYAN}"
    timeout = 10
    default_icon = dialog-information

[urgency_normal]
    background = "#${BG}"
    foreground = "#${FG}"
    frame_color = "#${BLUE}"
    highlight = "#${MAUVE}"
    timeout = 10
    default_icon = dialog-information

[urgency_critical]
    background = "#${BG}"
    foreground = "#${FG}"
    frame_color = "#${RED}"
    highlight = "#${RED}"
    timeout = 0
    default_icon = dialog-warning
EOF

chmod 600 "$tmp"
mv "$tmp" "$config"
trap - EXIT HUP INT TERM
